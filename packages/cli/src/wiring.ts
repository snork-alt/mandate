/**
 * Keys → env vars, the shell rc hook, the repo instructions section and the manifest of project-scope wiring.
 * Keys never go into agent config files: `~/.mandate/env.sh` (0600) exports MANDATE_KEY_<PROJECT>, and the shell rc
 * sources it (agents started from a shell, and VS Code-based editors which load the login shell env, see them).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { KeyStore } from '../../server/src/auth/keys.js';
import { envFile, keysFile, manifestFile, projectsFile, type Ctx } from './context.js';
import { change, MANAGED_MARK, readText, removeBlock, upsertBlock, type Change } from './edits.js';
import { envVarFor, serverName } from './agents.js';

export interface ProjectInfo {
  id: string;
  name: string;
  dataDir: string;
}

/** Registered projects (projects.json; empty when missing or unreadable). */
export function listProjects(ctx: Ctx): ProjectInfo[] {
  try {
    const j = JSON.parse(readFileSync(projectsFile(ctx), 'utf8')) as { projects?: ProjectInfo[] };
    return (j.projects ?? []).map((p) => ({ id: p.id, name: p.name, dataDir: p.dataDir }));
  } catch {
    return [];
  }
}

/** The agent key for each project (created when missing, like the server does on startup). */
export function projectKeys(ctx: Ctx, projects: string[]): Map<string, string> {
  const store = new KeyStore(keysFile(ctx));
  if (projects.length) store.ensureProjectKeys(projects);
  const out = new Map<string, string>();
  for (const k of store.list()) if (projects.includes(k.project) && !out.has(k.project)) out.set(k.project, k.key);
  return out;
}

const shq = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;

/** `byVar`: env var name → key. */
export function envSh(byVar: Map<string, string>): string {
  const lines = [...byVar].sort(([a], [b]) => a.localeCompare(b)).map(([v, k]) => `export ${v}=${shq(k)}`);
  return `# ${MANAGED_MARK}: agent keys for MCP configs (Authorization: Bearer \${MANDATE_KEY_<PROJECT>}).
# Regenerated by \`mandate install\` / \`mandate connect\`. Keep it private (0600); never commit it.
${lines.join('\n')}
`;
}

/** Keys already in env.sh (e.g. for a remote server's projects, added by `connect --url`). */
export function readEnvKeys(ctx: Ctx): Map<string, string> {
  const out = new Map<string, string>();
  for (const m of (readText(envFile(ctx)) ?? '').matchAll(/^export (MANDATE_KEY_[A-Z0-9_]+)='((?:[^']|'\\'')*)'$/gm)) out.set(m[1]!, m[2]!.replace(/'\\''/g, "'"));
  return out;
}

/** env.sh = existing lines (other servers' projects) + the given keys (by project id), which win. */
export function envChange(ctx: Ctx, keys: Map<string, string>): Change | null {
  const byVar = readEnvKeys(ctx);
  for (const [p, k] of keys) byVar.set(envVarFor(p), k);
  return change(envFile(ctx), envSh(byVar), 'agent key env vars', { private: true });
}

/** Shell rc files to hook: existing ~/.zshrc / ~/.bashrc, else the one for $SHELL. */
export function rcFiles(ctx: Ctx): string[] {
  const all = ['.zshrc', '.bashrc'].map((f) => path.join(ctx.home, f));
  const existing = all.filter((f) => existsSync(f));
  if (existing.length) return existing;
  const sh = path.basename(ctx.env.SHELL ?? '');
  return sh === 'zsh' ? [all[0]!] : sh === 'bash' ? [all[1]!] : [];
}

export function rcBody(ctx: Ctx): string {
  const f = envFile(ctx);
  const shown = f.startsWith(ctx.home + path.sep) ? `$HOME/${path.relative(ctx.home, f)}` : f;
  return `[ -f "${shown}" ] && . "${shown}"`;
}

export function rcChanges(ctx: Ctx, remove = false): (Change | null)[] {
  return rcFiles(ctx).map((f) => {
    const t = readText(f);
    if (!remove) return change(f, upsertBlock(t, 'env', rcBody(ctx), 'hash'), 'load Mandate agent keys');
    const after = removeBlock(t, 'env', 'hash');
    return change(f, after !== null && !after.trim() ? null : after, 'load Mandate agent keys');
  });
}

/* ------------------------------------------------------------------ repo instructions (CLAUDE.md / AGENTS.md) */

export function repoSection(project: string, url: string): string {
  return `## Mandate

This repo uses Mandate project \`${project}\` (MCP server \`${serverName(project)}\`, ${url}). For every feature, change or fix, follow the \`mandate\` skill (or the MCP server instructions); start with \`project_info\`, then \`code_context_set\` (again after each commit). Ask the user through Mandate (\`question_ask\`). Never change a standard without explicit user confirmation.
Commands: \`/mandate-flow on|off|status\`, \`/mandate-bootstrap\` (or the MCP prompts of the same names).`;
}

/** Which instruction files to write: the existing ones, else CLAUDE.md (Claude Code) and/or AGENTS.md (others). */
/**
 * Instruction files to carry the Mandate section: the ones each agent reads (CLAUDE.md, AGENTS.md shared by most,
 * GEMINI.md), written once per file. Files that already exist are always updated; no agents → AGENTS.md.
 */
export function instructionFiles(repo: string, agents: { caps: { instructions: string[] } }[]): string[] {
  const wanted = new Set(agents.flatMap((a) => a.caps.instructions));
  for (const f of KNOWN_INSTRUCTION_FILES) if (existsSync(path.join(repo, f))) wanted.add(f);
  if (!wanted.size) wanted.add('AGENTS.md');
  return [...wanted].map((f) => path.join(repo, f));
}

/** Instruction files the section may live in (for disconnect / uninstall). */
export const KNOWN_INSTRUCTION_FILES = ['CLAUDE.md', 'AGENTS.md', 'GEMINI.md'];

export function sectionChange(file: string, body: string | null): Change | null {
  const t = readText(file);
  if (body === null) {
    const after = removeBlock(t, 'section', 'html');
    return change(file, after !== null && !after.trim() ? null : after, 'Mandate section');
  }
  return change(file, upsertBlock(t, 'section', body, 'html'), 'Mandate section');
}

/* ------------------------------------------------------------------ manifest (project-scope wiring, for uninstall) */

export interface Manifest {
  version: 1;
  repos: { repo: string; project: string; agents: string[]; at: string }[];
}

export function readManifest(ctx: Ctx): Manifest {
  try {
    const m = JSON.parse(readFileSync(manifestFile(ctx), 'utf8')) as Manifest;
    return { version: 1, repos: m.repos ?? [] };
  } catch {
    return { version: 1, repos: [] };
  }
}

export function writeManifest(ctx: Ctx, m: Manifest): void {
  writeFileSync(manifestFile(ctx), `${JSON.stringify(m, null, 2)}\n`, { mode: 0o600 });
}
