import { quoteIdent } from './sql.js';
import type { Dialect, Driver } from './types.js';

export interface DialectScope {
  /** Postgres schema (ignored on SQLite). */
  schema?: string | null;
  /** Table-name prefix (`schemaPerProject: 'prefix'`, or a scoped SQLite database). */
  prefix?: string;
  /** Postgres: schema of each installed extension (`vector` → `extensions`). */
  extSchemas?: Record<string, string>;
}

const SQLITE_TYPES = { serialPk: 'INTEGER PRIMARY KEY', bigint: 'INTEGER', text: 'TEXT', blob: 'BLOB', real: 'REAL', bool: 'INTEGER' };
const PG_TYPES = { serialPk: 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', bigint: 'BIGINT', text: 'TEXT', blob: 'BYTEA', real: 'DOUBLE PRECISION', bool: 'SMALLINT' };

export function makeDialect(driver: Driver, scope: DialectScope = {}): Dialect {
  const pg = driver === 'postgres';
  const schema = pg ? (scope.schema ?? null) : null;
  const prefix = scope.prefix ?? '';
  const table = (name: string) => (schema ? `${quoteIdent(schema)}.${quoteIdent(prefix + name)}` : quoteIdent(prefix + name));
  const setList = (update: string[] | Record<string, string>) =>
    Array.isArray(update) ? update.map((c) => `${quoteIdent(c)} = excluded.${quoteIdent(c)}`).join(', ') : Object.entries(update).map(([c, e]) => `${quoteIdent(c)} = ${e}`).join(', ');
  const insert = (t: string, cols: string[], alias = '') => `INSERT INTO ${table(t)}${alias} (${cols.map(quoteIdent).join(', ')}) VALUES (${cols.map(() => '?').join(', ')})`;
  const extSchemas = scope.extSchemas ?? {};
  return {
    driver,
    schema,
    q: quoteIdent,
    table,
    index: (name: string) => quoteIdent(prefix + name),
    types: pg ? PG_TYPES : SQLITE_TYPES,
    upsert: (t, cols, conflict, update) => `${insert(t, cols, ' AS cur')} ON CONFLICT (${conflict.map(quoteIdent).join(', ')}) DO UPDATE SET ${setList(update)}`,
    insertIgnore: (t, cols) => `${insert(t, cols)} ON CONFLICT DO NOTHING`,
    skipLocked: pg ? ' FOR UPDATE SKIP LOCKED' : '',
    greatest: (a, b) => (pg ? `GREATEST(${a}, ${b})` : `max(${a}, ${b})`),
    jsonText: (col, key) => (pg ? `((${col})::jsonb ->> '${key.replace(/'/g, "''")}')` : `json_extract(${col}, '$.${key.replace(/'/g, "''")}')`),
    nowMs: pg ? '(EXTRACT(EPOCH FROM clock_timestamp()) * 1000)::bigint' : "CAST(unixepoch('subsec') * 1000 AS INTEGER)",
    ext: (name) => {
      const s = extSchemas[extensionOf(name)];
      return pg && s ? `${quoteIdent(s)}.${name}` : name;
    },
    extOp: (op) => {
      const s = extSchemas.vector ?? extSchemas.pg_trgm;
      return pg && s ? `OPERATOR(${quoteIdent(s)}.${op})` : op;
    },
  };
}

/** Which extension provides a type / function name (for schema qualification). */
function extensionOf(name: string): string {
  if (/^(vector|halfvec|sparsevec|cosine_distance|l2_distance|inner_product|vector_dims|vector_cosine_ops|vector_l2_ops|vector_ip_ops)$/.test(name)) return 'vector';
  if (/^(similarity|word_similarity|strict_word_similarity|show_trgm|gin_trgm_ops|gist_trgm_ops)$/.test(name)) return 'pg_trgm';
  return name;
}
